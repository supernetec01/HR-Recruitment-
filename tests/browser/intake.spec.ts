test('single-use update link supplements the existing record without an account', async ({ page, context }) => {
  await page.goto('/?page=candidates');
  await page.getByRole('button',{name:'Mở hồ sơ Trần Hoàng Nam',exact:true}).click();
  await page.getByRole('button',{name:'Mời bổ sung hồ sơ'}).click();
  await page.getByRole('button',{name:'Tạo liên kết',exact:true}).click();
  const link = await page.getByLabel('Liên kết dành riêng cho ứng viên').inputValue();
  await page.getByRole('button',{name:'Hoàn tất',exact:true}).click();
  const publicContext = await context.browser()!.newContext();
  const applicant = await publicContext.newPage();
  await applicant.goto(link);
  await applicant.getByLabel('Portfolio',{exact:true}).fill('https://example.com/portfolio-updated');
  await applicant.getByLabel('Tải CV (PDF hoặc DOCX)').setInputFiles({...pdf,name:'CV-version-3.pdf'});
  await applicant.getByRole('checkbox').check();
  await applicant.getByRole('button',{name:'Gửi thông tin bổ sung'}).click();
  await expect(applicant.getByRole('heading',{name:'Đã cập nhật, cảm ơn bạn!'})).toBeVisible();
  await applicant.reload();
  await expect(applicant.getByRole('alert')).toContainText('đã được sử dụng');
  await page.reload();
  await page.getByRole('button',{name:'CV & tài liệu (2)',exact:true}).click();
  await expect(page.getByText('CV-version-3.pdf',{exact:true})).toBeVisible();
  await expect(page.getByText('CV-demo-2.pdf',{exact:true})).toBeVisible();
  await publicContext.close();
});

